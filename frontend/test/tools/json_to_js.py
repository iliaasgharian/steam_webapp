#!/usr/bin/env python3
"""Turn the scraper's steam_games.json into js/steam-games-data.js (the file the website loads).

    python tools/json_to_js.py                      # reads data/steam_games.json
    python tools/json_to_js.py path/to/steam_games.json

Run it again every time you re-run scrape_steam_games.py, then reload the site (Ctrl+F5).
Why a .js file? A page opened straight from a folder (file://) is not allowed to fetch() a local .json,
but a <script> tag can load a .js file. Once the site is served by a real server/backend, the JSON can be fetched instead.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "data", "steam_games.json")
KEEP = ["id", "appid", "name", "developer", "publisher", "releaseDate", "comingSoon", "genres", "tags", "features", "price", "discount",
        "players", "peakYesterday", "delta", "reviews", "reviewCount", "reviewLabel", "metacritic", "shortDescription", "image",
        "screenshots", "platforms", "requirements", "website", "steamDeck"]   # big fields we do not need (e.g. the full DLC id list) are left out

with open(src, encoding="utf-8") as f:
    data = json.load(f)
games = []
for g in data["games"]:
    row = {k: g.get(k) for k in KEEP}
    row["dlcCount"] = len(g.get("dlc") or [])
    games.append(row)
out = os.path.join(ROOT, "js", "steam-games-data.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("// GENERATED by tools/json_to_js.py from steam_games.json — do not edit by hand.\n")
    f.write("const STEAM_GAMES_DATA = " + json.dumps({"scrapedAt": data.get("scrapedAt"), "games": games}, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"{len(games)} games -> {os.path.relpath(out, ROOT)} ({os.path.getsize(out) // 1024} KB)")
